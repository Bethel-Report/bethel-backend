CREATE TABLE publications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL CHECK (length(trim(title)) > 0),
    content TEXT NOT NULL CHECK (length(trim(content)) BETWEEN 1 AND 50000),
    type VARCHAR(20) NOT NULL CHECK (type IN ('ACTIVITY', 'GUIDANCE', 'ANNOUNCEMENT')),
    activity_date DATE,
    audience VARCHAR(20) NOT NULL CHECK (audience IN ('ALL_BETHELS', 'BETHELS', 'USERS')),
    display_from TIMESTAMP,
    display_until TIMESTAMP,
    CONSTRAINT chk_publication_display CHECK (
        display_until IS NULL OR (display_from IS NOT NULL AND display_until > display_from)
    ),
    CONSTRAINT chk_announcement_period CHECK (
        type <> 'ANNOUNCEMENT' OR (display_from IS NOT NULL AND display_until IS NOT NULL)
    ),
    author_id BIGINT NOT NULL REFERENCES users(id),
    bethel_id BIGINT REFERENCES bethels(id),
    timeline_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT chk_publication_activity CHECK (
        (type = 'ACTIVITY' AND activity_date IS NOT NULL AND bethel_id IS NOT NULL)
        OR (type <> 'ACTIVITY' AND activity_date IS NULL)
    )
);
CREATE INDEX idx_publications_timeline ON publications (timeline_at DESC, id DESC);
CREATE INDEX idx_publications_bethel_timeline
    ON publications (bethel_id, timeline_at DESC, id DESC);

CREATE TABLE publication_attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    publication_id BIGINT NOT NULL REFERENCES publications(id),
    object_key VARCHAR(255) NOT NULL UNIQUE,
    filename VARCHAR(255) NOT NULL,
    content_type VARCHAR(100) NOT NULL,
    size BIGINT NOT NULL CHECK (size > 0),
    created_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_publication_attachments_publication ON publication_attachments(publication_id);

CREATE TABLE storage_deletions (
    object_key VARCHAR(255) PRIMARY KEY,
    available_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_storage_deletions_available ON storage_deletions(available_at);

CREATE TABLE publication_target_bethels (
    publication_id BIGINT NOT NULL REFERENCES publications(id) ON DELETE CASCADE,
    bethel_id BIGINT NOT NULL REFERENCES bethels(id),
    PRIMARY KEY (publication_id, bethel_id)
);
CREATE INDEX idx_publication_target_bethel ON publication_target_bethels(bethel_id, publication_id);
CREATE TABLE publication_target_users (
    publication_id BIGINT NOT NULL REFERENCES publications(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id),
    PRIMARY KEY (publication_id, user_id)
);
CREATE INDEX idx_publication_target_user ON publication_target_users(user_id, publication_id);
