CREATE TABLE notifications (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title       VARCHAR(255) NOT NULL CHECK (length(trim(title)) > 0),
    content     TEXT NOT NULL CHECK (length(trim(content)) > 0),
    source_type VARCHAR(20) NOT NULL,
    resource_id BIGINT,
    bethel_id   BIGINT REFERENCES bethels(id),
    created_at  TIMESTAMP NOT NULL,
    CONSTRAINT ck_notifications_source_type
        CHECK (source_type IN ('PUBLICATION', 'FORM', 'REPORT'))
);

CREATE TABLE user_notifications (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES users(id),
    notification_id BIGINT NOT NULL REFERENCES notifications(id) ON DELETE CASCADE,
    seen            BOOLEAN NOT NULL DEFAULT false,
    read_at         TIMESTAMP,
    CONSTRAINT uq_user_notifications_user_notification UNIQUE (user_id, notification_id),
    CONSTRAINT ck_user_notifications_read_at CHECK ((seen AND read_at IS NOT NULL) OR
        (NOT seen AND read_at IS NULL))
);

CREATE INDEX idx_notifications_created_at ON notifications(created_at DESC, id DESC);
CREATE INDEX idx_notifications_source ON notifications(source_type, resource_id);
CREATE INDEX idx_user_notifications_user_unread ON user_notifications(user_id, seen, id);
CREATE INDEX idx_user_notifications_notification ON user_notifications(notification_id);
