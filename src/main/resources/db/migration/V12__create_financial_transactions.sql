CREATE TABLE financial_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bethel_id BIGINT NOT NULL REFERENCES bethels(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    type VARCHAR(10) NOT NULL CHECK (type IN ('RECEITA', 'DESPESA')),
    amount NUMERIC(19, 2) NOT NULL CHECK (amount > 0),
    transaction_date DATE NOT NULL,
    description VARCHAR(2000) NOT NULL CHECK (length(trim(description)) > 0),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_transactions_bethel_date
    ON financial_transactions (bethel_id, transaction_date DESC, id DESC);
CREATE INDEX idx_transactions_bethel_type_date
    ON financial_transactions (bethel_id, type, transaction_date DESC, id DESC);
