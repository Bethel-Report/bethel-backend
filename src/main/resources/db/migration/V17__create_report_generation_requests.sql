CREATE TABLE report_generation_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bethel_id BIGINT NOT NULL REFERENCES bethels(id),
    requester_id BIGINT NOT NULL REFERENCES users(id),
    type VARCHAR(20) NOT NULL CHECK (type IN ('FINANCEIRO', 'MEMBROS', 'PUBLICACOES')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('PENDING', 'PROCESSING', 'COMPLETED', 'FAILED')),
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    storage_key VARCHAR(512),
    failure_reason VARCHAR(1000),
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CHECK (period_start <= period_end)
);
CREATE INDEX idx_generation_requests_bethel_created
    ON report_generation_requests (bethel_id, created_at DESC);
