CREATE TABLE permissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id BIGINT NOT NULL UNIQUE,

    role VARCHAR(30) NOT NULL,

    bethel_id BIGINT,

    CONSTRAINT fk_permissions_user
        FOREIGN KEY (user_id)
        REFERENCES users (id),

    CONSTRAINT fk_permissions_bethel
        FOREIGN KEY (bethel_id)
        REFERENCES bethels (id),

    CONSTRAINT chk_permissions_role
        CHECK (
            role IN (
                'GRANDE_CONSELHO',
                'CONSELHO_DE_BETHEL',
                'MEMBRO_ATIVO',
                'MEMBRO_DE_MAIORIDADE'
            )
        ),

    CONSTRAINT chk_permissions_bethel
        CHECK (
            (
                role = 'GRANDE_CONSELHO'
                AND bethel_id IS NULL
            )
            OR
            (
                role <> 'GRANDE_CONSELHO'
                AND bethel_id IS NOT NULL
            )
        )
);