CREATE TABLE reports (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bethel_id        BIGINT      NOT NULL REFERENCES bethels(id),
    form_id          BIGINT      NOT NULL REFERENCES forms(id),
    status           VARCHAR(20) NOT NULL,
    submitted_at     TIMESTAMP,
    reopened_at      TIMESTAMP,
    reopen_deadline  TIMESTAMP,
    created_at       TIMESTAMP   NOT NULL,
    updated_at       TIMESTAMP,
    CONSTRAINT ck_reports_status CHECK (status IN ('DRAFT', 'SUBMITTED', 'REOPENED')),
    CONSTRAINT uq_reports_bethel_form UNIQUE (bethel_id, form_id)
);

CREATE TABLE report_answers (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id  BIGINT NOT NULL REFERENCES reports(id) ON DELETE CASCADE,
    field_id   BIGINT NOT NULL REFERENCES form_fields(id),
    value      TEXT,
    updated_at TIMESTAMP,
    CONSTRAINT uq_report_answers_report_field UNIQUE (report_id, field_id)
);

CREATE INDEX idx_reports_bethel_id ON reports(bethel_id);
CREATE INDEX idx_reports_form_id ON reports(form_id);
CREATE INDEX idx_reports_status ON reports(status);
CREATE INDEX idx_report_answers_report_id ON report_answers(report_id);
