CREATE TABLE forms (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(200)  NOT NULL,
    description    VARCHAR(2000),
    reference_year INTEGER       NOT NULL,
    status         VARCHAR(20)   NOT NULL,
    opening_date   DATE,
    closing_date   DATE,
    cloned_from_id BIGINT        REFERENCES forms(id),
    created_at     TIMESTAMP     NOT NULL,
    updated_at     TIMESTAMP,
    CONSTRAINT ck_forms_status CHECK (status IN ('DRAFT', 'PUBLISHED', 'CLOSED')),
    CONSTRAINT ck_forms_name_not_blank CHECK (length(trim(name)) > 0),
    CONSTRAINT ck_forms_closing_after_opening CHECK (
        closing_date IS NULL OR opening_date IS NULL OR closing_date > opening_date
    )
);

CREATE TABLE form_fields (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    form_id       BIGINT       NOT NULL REFERENCES forms(id) ON DELETE CASCADE,
    label         VARCHAR(300) NOT NULL,
    type          VARCHAR(20)  NOT NULL,
    required      BOOLEAN      NOT NULL DEFAULT false,
    display_order INTEGER      NOT NULL,
    CONSTRAINT ck_form_fields_type CHECK (type IN ('TEXT', 'NUMBER', 'DATE', 'BOOLEAN', 'SELECT')),
    CONSTRAINT ck_form_fields_label_not_blank CHECK (length(trim(label)) > 0),
    CONSTRAINT ck_form_fields_display_order_positive CHECK (display_order > 0)
);

CREATE TABLE form_field_options (
    field_id     BIGINT       NOT NULL REFERENCES form_fields(id) ON DELETE CASCADE,
    option_value VARCHAR(500) NOT NULL,
    option_order INTEGER      NOT NULL
);

CREATE INDEX idx_forms_status ON forms(status);
CREATE INDEX idx_forms_reference_year ON forms(reference_year);
CREATE INDEX idx_form_fields_form_id ON form_fields(form_id);
CREATE INDEX idx_form_field_options_field_id ON form_field_options(field_id);
