CREATE TABLE audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name VARCHAR(100) NOT NULL,
    record_id BIGINT NOT NULL,
    operation VARCHAR(10) NOT NULL CHECK (operation IN ('INSERT', 'UPDATE', 'DELETE')),
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    old_values JSONB,
    new_values JSONB,
    actor_id BIGINT NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    is_system BOOLEAN NOT NULL
);

CREATE INDEX idx_audit_log_table_record ON audit_log (table_name, record_id);
CREATE INDEX idx_audit_log_actor_time ON audit_log (actor_id, occurred_at DESC);

CREATE FUNCTION audit_row_change() RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    old_row JSONB;
    new_row JSONB;
    actor_email TEXT;
    actor_id_value BIGINT;
    system_operation BOOLEAN;
BEGIN
    IF TG_OP = 'UPDATE' AND to_jsonb(OLD) IS NOT DISTINCT FROM to_jsonb(NEW) THEN
        RETURN NEW;
    END IF;

    IF TG_OP <> 'INSERT' THEN
        old_row := to_jsonb(OLD);
    END IF;
    IF TG_OP <> 'DELETE' THEN
        new_row := to_jsonb(NEW);
    END IF;

    actor_id_value := NULLIF(current_setting('app.audit_user_id', true), '')::BIGINT;
    actor_email := NULLIF(current_setting('app.audit_user_email', true), '');
    system_operation := COALESCE(
        NULLIF(current_setting('app.audit_is_system', true), '')::BOOLEAN,
        actor_email IS NULL
    );

    IF actor_id_value IS NULL AND actor_email IS NOT NULL THEN
        SELECT u.id INTO actor_id_value
        FROM users u
        WHERE lower(u.email) = lower(actor_email)
        LIMIT 1;

        IF actor_id_value IS NULL
            AND TG_TABLE_NAME = 'users'
            AND TG_OP = 'INSERT'
            AND lower(new_row ->> 'email') = lower(actor_email) THEN
            actor_id_value := NEW.id;
        END IF;

        IF actor_id_value IS NOT NULL THEN
            PERFORM set_config('app.audit_user_id', actor_id_value::TEXT, true);
        END IF;
    END IF;

    IF system_operation AND actor_id_value IS NULL THEN
        IF TG_TABLE_NAME = 'users'
            AND TG_OP = 'INSERT'
            AND lower(new_row ->> 'email') = 'admin@bethelreport.local' THEN
            actor_id_value := NEW.id;
        ELSE
            SELECT u.id INTO actor_id_value
            FROM users u
            WHERE lower(u.email) = 'admin@bethelreport.local'
            LIMIT 1;
        END IF;
    END IF;

    IF actor_id_value IS NULL THEN
        RAISE EXCEPTION 'Could not resolve audit actor for %.%', TG_TABLE_NAME, TG_OP
            USING ERRCODE = '23514';
    END IF;

    INSERT INTO audit_log (table_name, record_id, operation, old_values, new_values,
        actor_id, is_system)
    VALUES (TG_TABLE_NAME,
        COALESCE((new_row ->> 'id')::BIGINT, (old_row ->> 'id')::BIGINT),
        TG_OP, old_row, new_row, actor_id_value, system_operation);

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

CREATE FUNCTION prevent_audit_log_mutation() RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'Audit log entries are immutable'
        USING ERRCODE = '23514';
END;
$$;

CREATE TRIGGER trg_audit_log_immutable
    BEFORE UPDATE OR DELETE ON audit_log
    FOR EACH ROW EXECUTE FUNCTION prevent_audit_log_mutation();

CREATE TRIGGER trg_audit_log_no_truncate
    BEFORE TRUNCATE ON audit_log
    FOR EACH STATEMENT EXECUTE FUNCTION prevent_audit_log_mutation();

DO $$
DECLARE
    audited_table TEXT;
BEGIN
    FOREACH audited_table IN ARRAY ARRAY[
        'users', 'permissions', 'bethels', 'invitations',
        'publications', 'financial_transactions'
    ] LOOP
        EXECUTE format(
            'CREATE TRIGGER %I AFTER INSERT OR UPDATE OR DELETE ON %I '
            'FOR EACH ROW EXECUTE FUNCTION audit_row_change()',
            'trg_audit_' || audited_table, audited_table);
    END LOOP;
END;
$$;
